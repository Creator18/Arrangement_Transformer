"""Voice clone with OUR pitch: RVC re-voices the TTS content in a VocalSet singer, singing exactly
the pitch track eval/sing_tts.py made (written notes + the approved few-cent drift).

RVC normally estimates pitch from its input (rmvpe).  Here its pitch step (Pipeline.get_f0) is
replaced by the known track, so nothing is estimated: the output's pitch IS the label.  Only
what is being said comes from the input (HuBERT content features); the waveform is generated by
RVC's own decoder, trained on real singers, so no vocoder sound reaches the result.

Run inside the RVC checkout with its environment:
    cd ~/tools/rvc && ~/envs/rvc/bin/python ~/arrangement_transformer/backend/eval/rvc_sing.py \\
        --model vocalset.pth --jobs jobs.json          # [{content, f0, out, speaker}, ...]
f0 files: .npy, Hz per 5 ms frame (0 = unvoiced), aligned with the content wav's start.
"""
import argparse, json, os, sys
from pathlib import Path

import numpy as np

RVC = Path.cwd(); sys.path.insert(0, str(RVC))
os.environ.setdefault("weight_root", str(RVC / "assets" / "weights"))
os.environ.setdefault("index_root", str(RVC / "logs"))
os.environ.setdefault("outside_index_root", str(RVC / "assets" / "indices"))
os.environ.setdefault("rmvpe_root", str(RVC / "assets" / "rmvpe"))

ap = argparse.ArgumentParser()
ap.add_argument("--model", required=True); ap.add_argument("--jobs", required=True)
ap.add_argument("--index", default=""); ap.add_argument("--index-rate", type=float, default=0.5)
ap.add_argument("--protect", type=float, default=0.33)
a = ap.parse_args()

from infer.cli import create_config            # noqa: E402
from infer.vc.modules import VC                # noqa: E402
from infer.vc.pipeline import Pipeline         # noqa: E402

TRACK = {"f0": None}                            # the pitch track of the current job, 200 fps


def known_f0(self, x, p_len, f0_up_key, f0_method):
    """Replacement for Pipeline.get_f0: our track, resampled onto RVC's frames (window 160 at
    16 kHz, audio padded by t_pad), then RVC's own unvoiced fill and coarse quantisation."""
    t = (np.arange(p_len) * self.window - self.t_pad) / self.sr          # seconds into the content wav
    src = TRACK["f0"]; ts = np.arange(len(src)) * 0.005
    f0 = np.interp(t, ts, src, left=0.0, right=0.0)
    f0[np.interp(t, ts, (src > 0).astype(float), left=0, right=0) < 0.5] = 0.0
    try:                                                                 # as RVC: fill unvoiced gaps
        uv = f0 == 0
        f0[uv] = np.interp(np.where(uv)[0], np.where(~uv)[0], f0[~uv])
    except Exception:                                                    # noqa: BLE001
        pass
    f0bak = f0.copy()
    lo, hi = 1127 * np.log(1 + 50 / 700), 1127 * np.log(1 + 1100 / 700)
    mel = 1127 * np.log(1 + f0 / 700)
    mel[mel > 0] = (mel[mel > 0] - lo) * 254 / (hi - lo) + 1
    mel = np.clip(mel, 1, 255)
    return np.rint(mel).astype(np.int32), f0bak


Pipeline.get_f0 = known_f0

import soundfile as sf                          # noqa: E402

vc = VC(create_config()); vc.get_vc(a.model)
for job in json.loads(Path(a.jobs).read_text()):
    if Path(job["out"]).exists():                                        # resumable
        continue
    TRACK["f0"] = np.load(job["f0"]).astype(np.float64)
    status, res = vc.vc_single(int(job.get("speaker", 0)), job["content"], 0, "rmvpe", a.index,
                               a.index_rate if a.index else 0.0, 0, 1.0, a.protect)
    if res is None or res[1] is None:
        print("FAILED", job["out"], status, flush=True); continue
    sr, y = res
    Path(job["out"]).parent.mkdir(parents=True, exist_ok=True)
    sf.write(job["out"], y, sr); print("ok", job["out"], sr, flush=True)
